
WITH cleaned AS (
    SELECT
        ID::VARCHAR AS ID,

        TO_TIMESTAMP_NTZ(DATETIME, 0) AS DATETIME,

        TRIM(CATEGORY)::VARCHAR AS CATEGORY,
        TRIM(HEADLINE)::VARCHAR AS HEADLINE,
        TRIM(IMAGE)::VARCHAR AS IMAGE,

        TRIM(UPPER(RELATED))::VARCHAR AS RELATED,

        TRIM(SOURCE)::VARCHAR AS SOURCE,
        TRIM(SUMMARY)::VARCHAR AS SUMMARY,
        TRIM(URL)::VARCHAR AS URL,

        PUBLISHED_DATE::TIMESTAMP_TZ AS PUBLISHED_DATE

    FROM {{ source('project_raw', 'NEWS_OWENS_C') }}
)

SELECT *
FROM cleaned
WHERE ID IS NOT NULL

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY ID
    ORDER BY DATETIME DESC NULLS LAST
) = 1

